import test from 'node:test';
import assert from 'node:assert/strict';
import { createServices, createInvitationUrl, readInvitationToken } from '../src/api/index.js';
import { createWorkspaceApi } from '../src/workspace.js';

const baseUrl = process.env.TEST_API_URL;
test('real backend: two accounts, groups, invitations, tracks, votes and access', { skip: !baseUrl }, async () => {
  const suffix = `${Date.now()}_${Math.floor(Math.random() * 10000)}`;
  const alice = createServices({ baseUrl }), bob = createServices({ baseUrl });
  const a = { username: `a_${suffix}`, password: 'Test-pass-124' };
  const b = { username: `b_${suffix}`, password: 'Test-pass-125' };
  await alice.auth.register(a); await bob.auth.register(b);
  await assert.rejects(alice.auth.register(a), { status: 409 });
  await assert.rejects(alice.auth.login({ ...a, password: 'Wrong-pass' }), { status: 401 });
  await alice.auth.login(a); await bob.auth.login(b);
  const profile = await alice.request('/auth/me'); assert.equal(profile.username, a.username);
  const aliceSpace = createWorkspaceApi(alice), bobSpace = createWorkspaceApi(bob);
  await aliceSpace.initialize(profile); await bobSpace.initialize(await bob.request('/auth/me'));
  const group = await aliceSpace.create({ name: ' <Волна & друзья> ' });
  assert.equal(group.name, '<Волна & друзья>'); assert.equal(group.membersCount, 1);
  assert.equal((await aliceSpace.list()).some((g) => g.id === group.id), true);
  assert.equal((await bobSpace.list()).some((g) => g.id === group.id), false);
  await assert.rejects(bob.playlists.get(group.id), { status: 403 });
  if (!bobSpace.localGroups) await assert.rejects(bob.playlists.invitation(group.id), { status: 403 });
  const invitation = await aliceSpace.invitation(group.id);
  assert.equal(invitation.invite_token, group.inviteToken);
  const link = createInvitationUrl(invitation.invite_token, 'http://localhost:5173/');
  assert.equal((await bobSpace.join(readInvitationToken(link))).membersCount, 2);
  assert.equal((await bobSpace.join(invitation.invite_token)).membersCount, 2);
  assert.equal((await alice.playlists.get(group.id)).inviteToken, null);
  const track = await alice.tracks.add({ title: 'Дорога домой', artist: 'Тестовый исполнитель', communityId: group.id });
  await bob.tracks.add({ title: '<script>не HTML</script>', artist: 'A & B', communityId: group.id });
  await bobSpace.vote(track.id, -1);
  let tracks = await bobSpace.tracks(group.id);
  assert.equal(tracks.find((t) => t.id === track.id).my_vote, -1);
  assert.equal(tracks.find((t) => t.id === track.id).score, -1);
  await aliceSpace.vote(track.id, 1);
  tracks = await bobSpace.tracks(group.id);
  assert.equal(tracks.find((t) => t.id === track.id).score, 0);
  assert.equal(tracks.find((t) => t.id === track.id).my_vote, -1);
  await bobSpace.vote(track.id, 1);
  assert.equal((await bobSpace.tracks(group.id)).find((t) => t.id === track.id).score, 2);
  await bobSpace.vote(track.id, 0);
  assert.equal((await bobSpace.tracks(group.id)).find((t) => t.id === track.id).score, 1);
  await assert.rejects(bobSpace.join('missing-invite'), { status: 404 });
  alice.auth.logout();
  await assert.rejects(aliceSpace.list(), { status: 401 });
});
